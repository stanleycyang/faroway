export function getCostLevel(
  multiplier: number,
): "Budget-Friendly" | "Moderate" | "Above Average" | "Expensive" {
  if (multiplier <= 0.55) return "Budget-Friendly";
  if (multiplier <= 0.95) return "Moderate";
  if (multiplier <= 1.3) return "Above Average";
  return "Expensive";
}
